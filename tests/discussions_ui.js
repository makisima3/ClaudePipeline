async (page) => {
  const base = new URL(page.url()).origin;
  const get = async path => (await fetch(base + path)).json();
  const info = await get('/api/demo/info');
  const assert = (ok, msg) => { if (!ok) throw new Error(msg); };
  const checks = {}, errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Мастерская', exact: true }).click();
  await page.getByRole('button', { name: 'Доска', exact: true }).click();
  if (await page.locator('#chat').isHidden()) await page.getByRole('button', { name: 'Чат', exact: true }).click();
  await page.waitForFunction(() => S.chat.pid === S.projectId && D.key);
  await page.locator('#chatInput').fill('Кнопки мелкие, давай обсудим результат');
  await page.locator('#chatFile').setInputFiles({ name: 'замечания.txt', mimeType: 'text/plain', buffer: Buffer.from('Кнопки 44 px') });
  const initial = await get('/api/demo/discussions');
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator('#view .result-entry').first().waitFor();
  const id = await page.locator('#view .result-entry').first().getAttribute('id');
  const rid = Number(id.split('-').at(-1));
  await page.locator(`#${id} .discuss-result`).click();
  await page.locator('#chatContext .task-context').waitFor();
  await page.waitForFunction(() => S.chat.pid === S.projectId && !!D.value.context);
  assert(await page.locator('#chatInput').inputValue() === 'Кнопки мелкие, давай обсудим результат', 'Текст потерян');
  assert(await page.locator('#chatAtts').textContent().then(x => x.includes('замечания.txt')), 'Файл потерян');
  assert((await get('/api/demo/discussions')).runs === initial.runs, 'Обсудить запустило агента');
  assert((await get(`/api/projects/${info.project_id}/chats`)).chats.length === 1, 'Создан лишний чат');
  checks.attachWithoutSend = true;
  await page.screenshot({ path: 'output/playwright/task-26/desktop-draft.png' });
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator(`#${id} .discuss-result`).click();
  assert((await get(`/api/projects/${info.project_id}/chats`)).chats.length === 1, 'Повтор создал чат');
  checks.repeat = true;
  await page.getByRole('button', { name: 'Личный сайт', exact: true }).click();
  await page.waitForFunction(() => S.chat.pid === S.projectId);
  assert(await page.locator('#chatInput').inputValue() === '' && await page.locator('#chatContext').isHidden(), 'Контекст перешёл в другой проект');
  await page.getByRole('button', { name: 'Мастерская', exact: true }).click();
  await page.locator('#chatContext .task-context').waitFor();
  await page.getByRole('button', { name: 'Новый', exact: true }).click();
  await page.waitForFunction(cid => S.chat.id !== cid, info.chat_id);
  assert(await page.locator('#chatInput').inputValue() === '' && await page.locator('#chatContext').isHidden(), 'Контекст перешёл в другой чат');
  await page.locator('#chatPick').click();
  await page.locator('.chat-item').filter({ hasText: 'Работа над проектом' }).click();
  await page.locator('#chatContext .task-context').waitFor();
  await page.reload();
  await page.locator('#chatContext .task-context').waitFor();
  assert(await page.locator('#chatInput').inputValue() === 'Кнопки мелкие, давай обсудим результат', 'Черновик не восстановлен');
  assert(await page.locator('#chatAtts').textContent().then(x => x.includes('замечания.txt')), 'File не восстановлен из IndexedDB');
  checks.scopedPersistentDrafts = true;
  await page.getByRole('button', { name: 'Убрать прикреплённую задачу' }).click();
  assert(await page.locator('#chatContext').isHidden(), 'Не снято прикрепление');
  assert(await page.locator('#chatInput').inputValue() !== '', 'Удаление контекста удалило текст');
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator(`#${id} .discuss-result`).click();
  checks.remove = true;
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Выход за ширину телефона');
  await page.screenshot({ path: 'output/playwright/task-26/mobile-draft.png' });
  checks.mobile = true;
  // Сервер принял запрос, но клиент потерял ответ. Повтор должен вернуть квитанцию без второй модели/файла.
  let intercepted = false;
  await page.route('**/api/chats/*/messages', async route => {
    if (route.request().method() !== 'POST' || intercepted) return route.continue();
    intercepted = true; await route.fetch(); await route.abort('failed');
  });
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => D.value.pending && !S.chatSending);
  assert(await page.locator('#chatInput').isDisabled(), 'Неоднозначная отправка позволяет изменить запрос');
  await page.reload();
  await page.waitForFunction(() => D.value.pending);
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !D.value.pending && !S.chatSending);
  const after = await get('/api/demo/discussions');
  assert(after.runs === initial.runs + 1, 'Повтор запустил вторую модель');
  const sent = after.messages.filter(m => m.task_context);
  assert(sent.length === 1 && sent[0].task_context.result_id === rid, 'Нет структурированного результата в истории');
  assert(sent[0].attachments.length === 1, 'Вложение не сохранено');
  assert(await (await fetch(base + `/api/chat/${sent[0].id}/files/0`)).text() === 'Кнопки 44 px', 'Байты File потеряны');
  assert(await page.locator('#chatInput').inputValue() === '', 'Черновик не очищен после квитанции');
  checks.lostReceiptIdempotency = true;
  await page.unroute('**/api/chats/*/messages');
  await page.locator('#chatInput').fill('Кнопки мелкие, создай задачу на увеличение');
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !S.chatSending && S.chat.messages.some(m => m.text?.includes('Создана связанная задача')));
  const followup = (await get('/api/demo/discussions')).tasks.find(t => t.title === 'Увеличить кнопки');
  assert(followup, 'Заглушка не создала продолжение');
  const linked = await get(`/api/tasks/${followup.id}`);
  assert(linked.links.some(t => t.task_id === sent[0].task_context.task_id), 'Нет двусторонней связи');
  assert(linked.telegram_notify === 0, 'Флаг скопирован из исходной задачи вместо устройства');
  assert((await get(`/api/tasks/${sent[0].task_context.task_id}`)).status === 'done', 'Исходная задача изменена');
  checks.linkedFollowupWithStub = true;
  await page.screenshot({ path: 'output/playwright/task-26/mobile-history.png' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.reload();
  await page.locator('#msgs .task-context').waitFor();
  await page.screenshot({ path: 'output/playwright/task-26/desktop-history.png' });
  checks.history = true;
  await page.getByRole('button', { name: 'Новый', exact: true }).click();
  await page.waitForFunction(() => !D.value.context && !S.chat.messages.length);
  await page.locator('#chatInput').fill('Обычное сообщение без прикрепления');
  await page.context().setOffline(true);
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => D.value.pending && !S.chatSending);
  assert(await page.locator('#chatInput').inputValue() === 'Обычное сообщение без прикрепления', 'Офлайн потерял текст');
  await page.context().setOffline(false);
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !D.value.pending && !S.chatSending);
  checks.offlineAndOrdinaryMessages = true;
  assert(!errors.length, errors.join('; '));
  return { checks, javascriptErrors: errors };
}
