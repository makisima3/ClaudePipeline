async (page) => {
  const base = new URL(page.url()).origin;
  const info = await (await fetch(base + '/api/demo/info')).json();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const checks = {};
  await page.getByRole('button', { name: 'Мастерская', exact: true }).click();
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator('.result-entry').first().waitFor();
  assert(await page.locator('#view .result-entry').count() >= 4, 'Нет общей истории');
  checks.history = true;
  const firstImage = page.locator('#view .result-file img').first();
  await firstImage.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => [...document.querySelectorAll('#view .result-file img')].some(i => i.complete && i.naturalWidth > 0));
  checks.image = true;
  const video = page.locator('#view video').first();
  await video.scrollIntoViewIfNeeded();
  await video.evaluate(v => v.play());
  await page.waitForFunction(() => document.querySelector('#view video').currentTime > 0);
  await video.evaluate(v => v.pause());
  checks.video = true;
  const downloadWait = page.waitForEvent('download');
  await page.locator('#view .result-file a[download]').filter({ hasText: 'инструкция.txt' }).first().click();
  const download = await downloadWait;
  assert(download.suggestedFilename() === 'инструкция.txt', 'Имя скачанного файла');
  checks.download = true;
  await page.locator('#view').evaluate(el => el.scrollTop = 0);
  await page.getByRole('button', { name: 'Всё прочитано', exact: true }).click();
  assert(await page.locator('#rbadge .badge').count() === 0, 'Непрочитанное не сброшено');
  checks.read = true;
  await page.locator('#view .result-actions button.ghost').first().click();
  await page.getByText('Полный отчёт этого завершения', { exact: true }).click();
  assert(await page.locator('#modal details[open]').count() === 1, 'Отчёт не открыт');
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  checks.report = true;
  await page.getByRole('button', { name: 'Личный сайт', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#view .result-entry h3')?.textContent === 'Отдельный результат другого проекта');
  assert(await page.locator('#view .result-entry').count() === 1, 'Смешались проекты');
  checks.projects = true;
  await page.getByRole('button', { name: 'Мастерская', exact: true }).click();
  await page.waitForFunction(() => R.pid === S.projectId && R.items.length >= 4);
  await page.context().setOffline(true);
  const r = await (await fetch(base + '/api/demo/finish', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Восстановление после офлайна' }) })).json();
  await page.context().setOffline(false);
  await page.waitForFunction(id => !!document.querySelector(`#view #result-${id}`), r.id, { timeout: 30000 });
  checks.offlineRecovery = true;
  await page.reload();
  await page.locator(`#view #result-${r.id}`).waitFor();
  assert(await page.locator(`#view #result-${r.id}`).count() === 1, 'Дубль после перезагрузки');
  checks.reload = true;
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.locator('#view').evaluate(el => el.scrollTop = 0);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Горизонтальный выход за экран');
    await page.screenshot({ path: `output/playwright/task-24/results-${width}.png` });
  }
  checks.responsive = true;
  await page.goto(base + `/?result_id=${r.id}`);
  await page.locator('#modal .result-entry').waitFor();
  assert(await page.locator('#modal h3').first().textContent() === 'Мастерская #' + r.task_number, 'Прямая ссылка на результат');
  checks.deepLink = true;
  assert(errors.length === 0, 'Ошибки JavaScript: ' + errors.join('; '));
  return checks;
}
