async (page) => {
  const base = new URL(page.url()).origin;
  const get = async path => (await fetch(base + path)).json();
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const info = await get('/api/demo/info');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Мастерская', exact: true }).click();
  await page.getByRole('button', { name: 'Доска', exact: true }).click();
  if (await page.locator('#chat').isHidden()) await page.getByRole('button', { name: 'Чат', exact: true }).click();
  await page.getByRole('button', { name: 'Новый', exact: true }).click();
  await page.waitForFunction(() => !S.chat.messages.length && S.chats.find(c => c.id === S.chat.id)?.title === null);
  if (await page.locator('#chatContext .context-remove').count()) await page.getByRole('button', { name: 'Убрать прикреплённую задачу' }).click();
  await page.locator('#chatInput').fill('Текст при замене и устаревшем результате');
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator('#view .discuss-result').first().click();
  await page.waitForFunction(() => !!D.value.context);
  const first = await page.evaluate(() => D.value.context.result_id);
  const pageData = await get(`/api/projects/${info.project_id}/results`);
  const second = pageData.items.find(r => r.id !== first);
  await page.getByRole('button', { name: /^Результаты/ }).click();
  // CLI сам перехватывает modal dialogs; проверяем обе ветки решения, нативный confirm проверяется в APK.
  await page.evaluate(() => { window.__originalConfirm = window.confirm; window.__confirmCalls = 0; window.confirm = () => { window.__confirmCalls++; return false; }; });
  await page.locator(`#result-${second.id} .discuss-result`).click();
  await page.waitForFunction(() => window.__confirmCalls === 1);
  assert(await page.evaluate(() => D.value.context.result_id) === first, 'Отмена подменила результат');
  await page.evaluate(() => { window.confirm = () => { window.__confirmCalls++; return true; }; });
  await page.locator(`#result-${second.id} .discuss-result`).click();
  await page.waitForFunction(id => D.value.context.result_id === id, second.id);
  await page.evaluate(() => { window.confirm = window.__originalConfirm; });
  assert(await page.locator('#chatInput').inputValue() === 'Текст при замене и устаревшем результате', 'Замена потеряла текст');
  const before = await get('/api/demo/discussions');
  await page.evaluate(() => { D.value.context.result_id = 99999999; draftSave(); });
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !S.chatSending && !D.value.pending);
  assert(await page.locator('#chatInput').inputValue() !== '', 'Недоступный результат потерял текст');
  assert((await get('/api/demo/discussions')).runs === before.runs, 'Недоступный контекст запустил агента');
  await page.getByRole('button', { name: 'Убрать прикреплённую задачу' }).click();
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !S.chatSending);
  assert((await get('/api/demo/discussions')).runs === before.runs + 1, 'Обычное сообщение не отправилось после снятия');
  const deleted = await (await fetch(base + '/api/demo/finish', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Удалённая карточка для обсуждения' }) })).json();
  await fetch(base + `/api/tasks/${deleted.source_task_id}`, { method: 'DELETE' });
  await page.getByRole('button', { name: /^Результаты/ }).click();
  await page.locator(`#result-${deleted.id} .discuss-result`).click();
  await page.waitForFunction(id => D.value.context?.result_id === id, deleted.id);
  assert(await page.locator('#chatContext').textContent().then(x => x.includes('карточка удалена')), 'Удалённая карточка не обозначена');
  assert(await page.locator('#chatContext').getByRole('button', { name: 'Карточка', exact: true }).count() === 0, 'Ложный переход к удалённой карточке');
  await page.locator('#chatInput').fill('Обсудим сохранённый исторический итог');
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  await page.waitForFunction(() => !S.chatSending);
  await page.getByRole('button', { name: 'Личный сайт', exact: true }).click();
  await page.waitForFunction(() => S.chat.pid === S.projectId && !S.chat.id);
  await page.locator('#chatInput').fill('Первый черновик проекта без чатов');
  await page.locator('#chatFile').setInputFiles({ name: 'first.txt', mimeType: 'text/plain', buffer: Buffer.from('first draft') });
  const otherResult = (await get(`/api/projects/${info.second_project_id}/results`)).items[0];
  const beforeFirst = (await get('/api/demo/discussions')).runs;
  await page.evaluate(id => Promise.all([App.discussResult(id), App.discussResult(id)]), otherResult.id);
  assert((await get(`/api/projects/${info.second_project_id}/chats`)).chats.length === 1, 'Двойное нажатие создало несколько чатов');
  assert(await page.locator('#chatInput').inputValue() === 'Первый черновик проекта без чатов', 'Создание чата потеряло текст');
  assert(await page.locator('#chatAtts').textContent().then(x => x.includes('first.txt')), 'Создание чата потеряло файл');
  assert((await get('/api/demo/discussions')).runs === beforeFirst, 'Первый чат запустил агента');
  return { replacementCancelAndAccept: true, staleDraftPreservesText: true, removeThenOrdinarySend: true,
    deletedTaskDiscussion: true, firstChatAndDoubleClickPreserveDraft: true };
}
